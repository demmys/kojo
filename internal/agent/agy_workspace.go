// The Antigravity CLI (agy) has no per-invocation flag for MCP servers or
// for the system prompt. It reads both from the workspace — the process
// cwd, which for a kojo turn is the agent directory:
//
//   - <dir>/.agents/mcp_config.json  MCP servers ({"mcpServers": {...}})
//   - <dir>/.agents/agents/<name>/agent.md  a custom agent, selected with
//     --agent <name>; it selects tools, but not the per-turn prompt
//   - <dir>/.agents/rules/kojo-system-*.md  always_on prompt rules, read
//     again on resumed conversations (custom agent bodies are frozen)
//
// kojo owns both files and rewrites them before every turn. One agent can
// run several agy turns at once (its own chat plus keyed external
// sessions) and they share the files, so a turn that needs them to say
// something else waits until the turns started against the current
// content have exited (the same scheme as holdGrokMCPConfig).

const (
	agyKojoAgentName = "kojo"
	// agyMCPTimeoutSeconds lifts agy's per-call MCP limit (3 minutes):
	// kojo's own MCP tools (exec, long searches) can run far longer, and
	// the turn timeout already bounds the run.
	agyMCPTimeoutSeconds = 3600
)

func agyMCPConfigPath(agentDirPath string) string {
	return filepath.Join(agentDirPath, ".agents", "mcp_config.json")
}

func agyAgentDefPath(agentDirPath string) string {
	return filepath.Join(agentDirPath, ".agents", "agents", agyKojoAgentName, "agent.md")
}

// agyWorkspaceMu guards the managed files and agyWorkspaceHolds.
var agyWorkspaceMu sync.Mutex

type agyWorkspaceHold struct {
	key   string
	users int
	freed chan struct{} // closed when users drops to zero
}

var agyWorkspaceHolds = map[string]*agyWorkspaceHold{}

// renderAgyMCPConfig renders mcp_config.json, or "" when there is nothing
// to declare (the file is then removed).
func renderAgyMCPConfig(servers map[string]mcpServerEntry) (string, error) {
	type entry struct {
		Command        string            `json:"command,omitempty"`
		Args           *[]string         `json:"args,omitempty"`
		Env            map[string]string `json:"env,omitempty"`
		ServerURL      string            `json:"serverUrl,omitempty"`
		Headers        map[string]string `json:"headers,omitempty"`
		TimeoutSeconds int               `json:"timeoutSeconds"`
	}
	out := map[string]entry{}
	for name, e := range servers {
		if name == "" || (e.Command == "" && e.URL == "") {
			continue
		}
		if e.isStdio() {
			args := e.Args
			if args == nil {
				args = []string{}
			}
			out[name] = entry{Command: e.Command, Args: &args, Env: e.Env, TimeoutSeconds: agyMCPTimeoutSeconds}
		} else {
			out[name] = entry{ServerURL: e.URL, Headers: e.Headers, TimeoutSeconds: agyMCPTimeoutSeconds}
		}
	}
	if len(out) == 0 {
		return "", nil
	}
	b, err := json.MarshalIndent(map[string]any{"mcpServers": out}, "", "  ")
	if err != nil {
		return "", err
	}
	return string(b) + "\n", nil
}

// agyAgentTools is the tool set of the kojo custom agent. A custom agent
// gets only the tools its frontmatter lists (none without the key), and
// names agy does not know fail the whole run, so this is the default
// agent's tool set minus the names agy 1.4.8 refuses there (browser_*,
// command_status, ...) and minus schedule / search_marketplace, which
// kojo does not want agents to use. MCP servers from mcp_config.json are
// reachable regardless (call_mcp_tool is added by agy).
var agyAgentTools = []string{
	"ask_custom_permission", "ask_permission", "ask_question", "define_subagent",
	"find_by_name", "finish", "generate_image", "grep_search", "invoke_subagent",
	"list_dir", "list_plugin_accounts", "manage_subagents", "manage_task",
	"multi_replace_file_content", "notebook_edit", "read_url_content",
	"replace_file_content", "run_command", "run_workflow", "search_web",
	"send_message", "view_file", "wait", "write_to_file",
}

// renderAgyAgentDef keeps the upstream custom tool policy. The body must
// stay static: agy freezes it when a conversation is created, whereas
// the always_on workspace rules carry the current prompt on every turn.
func renderAgyAgentDef(systemPrompt string) string {
	if systemPrompt == "" {
		return ""
	}
	return "---\nname: " + agyKojoAgentName +
		"\ndescription: kojo agent (generated by kojo for every turn; edits are lost)" +
		"\ntools: [" + strings.Join(agyAgentTools, ", ") + "]" +
		"\n---\nFollow the current kojo instructions in .agents/rules/kojo-system-*.md. " +
		"Those rules are refreshed every turn; the latest version replaces earlier kojo rule snapshots in the conversation.\n"
}

// holdAgyWorkspace makes the managed files say exactly files (path →
// content; "" removes the file) and keeps them that way until release is
// called, which the caller does once its agy process has exited.
func holdAgyWorkspace(ctx context.Context, agentDirPath string, files map[string]string) (release func(), err error) {
	key := agyWorkspaceKey(files)
	for {
		agyWorkspaceMu.Lock()
		hold := agyWorkspaceHolds[agentDirPath]
		if hold != nil && hold.key != key {
			freed := hold.freed
			agyWorkspaceMu.Unlock()
			select {
			case <-freed:
				continue
			case <-ctx.Done():
				return nil, ctx.Err()
			}
		}
		// Also under a hold of the same content: the files may have been
		// edited since, and putting back what the running turns were
		// started with takes nothing from them.
		if err := prepareAgyManagedPaths(agentDirPath, files); err != nil {
			agyWorkspaceMu.Unlock()
			return nil, err
		}
		for path, content := range files {
			if err := syncAgyManagedFile(path, content); err != nil {
				agyWorkspaceMu.Unlock()
				return nil, err
			}
		}
		if hold == nil {
			hold = &agyWorkspaceHold{key: key, freed: make(chan struct{})}
			agyWorkspaceHolds[agentDirPath] = hold
		}
		hold.users++
		agyWorkspaceMu.Unlock()

		var once sync.Once
		return func() {
			once.Do(func() {
				agyWorkspaceMu.Lock()
				defer agyWorkspaceMu.Unlock()
				if hold.users--; hold.users == 0 {
					delete(agyWorkspaceHolds, agentDirPath)
					close(hold.freed)
				}
			})
		}, nil
	}
}

// Check every managed parent before writing or removing anything. A
// symlink in the writable workspace must not redirect MCP tokens or rules
// outside the agent directory. Only kojo's numbered rule files are pruned.
func prepareAgyManagedPaths(dir string, files map[string]string) error {
	paths := []string{filepath.Join(dir, ".agents"), agyRulesDir(dir)}
	for path := range files {
		rel, err := filepath.Rel(dir, path)
		if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
			return fmt.Errorf("agy managed path outside agent directory: %s", path)
		}
		for parent := filepath.Dir(path); parent != dir; parent = filepath.Dir(parent) {
			paths = append(paths, parent)
		}
	}
	if err := geminiRefuseSymlinks(paths...); err != nil {
		return err
	}
	entries, err := os.ReadDir(agyRulesDir(dir))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasPrefix(name, agyRulesFilePrefix) || !strings.HasSuffix(name, ".md") {
			continue
		}
		path := filepath.Join(agyRulesDir(dir), name)
		if _, keep := files[path]; !keep {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

func agyWorkspaceKey(files map[string]string) string {
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	h := sha256.New()
	for _, p := range paths {
		h.Write([]byte(p))
		h.Write([]byte{0})
		h.Write([]byte(files[p]))
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))
}

// syncAgyManagedFile writes content to path (0600: an HTTP MCP entry
// carries the agent's kojo token) unless it already says that, or removes
// path when content is "".
func syncAgyManagedFile(path, content string) error {
	if err := agyRefuseFileSymlink(path); err != nil {
		return err
	}
	if content == "" {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	if cur, err := os.ReadFile(path); err == nil && string(cur) == content {
		// A file someone else created with the same content may be
		// world-readable.
		return os.Chmod(path, 0o600)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".kojo-*.tmp")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		os.Remove(tmpPath)
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpPath)
		return err
	}
	if err := os.Rename(tmpPath, path); err != nil {
		os.Remove(tmpPath)
		return err
	}
	return nil
}
